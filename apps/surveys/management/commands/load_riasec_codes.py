class Command(BaseCommand):
    help = "Загружает 120 интерпретаций трёхбуквенных кодов RIASEC"

    def handle(self, *args, **options):
        created = 0
        updated = 0

        for item in RIASEC_CODES:
            code = item["code"]

            if len(code) != 3:
                self.stderr.write(f"Пропущен код {code}: длина не 3")
                continue

            obj, was_created = RiasecCodeInterpretation.objects.update_or_create(
                code=code,
                defaults={
                    "dominant": code[0],
                    "secondary": code[1],
                    "tertiary": code[2],
                    "description": item["description"].strip(),
                    "professions": item["professions"].strip(),
                    "is_active": True,
                },
            )

            if was_created:
                created += 1
            else:
                updated += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"Готово: создано {created}, обновлено {updated}, всего {len(RIASEC_CODES)}"
            )
        )
